#!/usr/bin/env python3
"""Build local Chrome and Firefox packages from the shipped Safari UI; never read the vault."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
FILES = ("detector.js", "content.js", "background.js", "popup.js", "popup.html", "icon-48.png", "icon-96.png", "icon-128.png")
HOST = "io.snackstud.pistachio"
FIREFOX_ID = "pistachio@snackstud.io"


def package(target, output):
    source = ROOT / "App/Safari/Resources"
    manifest = json.loads((source / "manifest.json").read_text())
    manifest["name"] = "Pistachio for " + target.title()
    manifest["permissions"].append("scripting")
    manifest["host_permissions"] = ["<all_urls>"]
    manifest["content_scripts"][0]["js"] = ["browser-config.js", "browser-api.js", "detector.js", "content.js"]
    if target == "chrome":
        manifest["minimum_chrome_version"] = "120"
        manifest["background"] = {"service_worker": "background-worker.js"}
    else:
        manifest["background"] = {"scripts": ["browser-config.js", "browser-api.js", "background.js"]}
        manifest["browser_specific_settings"] = {"gecko": {
            "id": FIREFOX_ID, "strict_min_version": "142.0",
            "data_collection_permissions": {"required": ["authenticationInfo", "websiteActivity", "websiteContent"]}
        }}
    with tempfile.TemporaryDirectory(prefix="pistachio-extension-") as temp:
        stage = Path(temp)
        for name in FILES:
            shutil.copy2(source / name, stage / name)
        for name in ("background.js", "popup.js", "content.js"):
            body = (stage / name).read_text()
            (stage / name).write_text("(function (browser) {\n" + body + "\n})(globalThis.PistachioBrowserAPI);\n")
        shutil.copy2(ROOT / "App/Browser/browser-api.js", stage / "browser-api.js")
        config = {"target": target, "host": HOST}
        (stage / "browser-config.js").write_text("globalThis.PistachioBrowserConfig = " + json.dumps(config) + ";\n")
        if target == "chrome":
            (stage / "background-worker.js").write_text('importScripts("browser-config.js", "browser-api.js", "background.js");\n')
        popup = (stage / "popup.html").read_text().replace('<script src="popup.js">',
            '<script src="browser-config.js"></script>\n  <script src="browser-api.js"></script>\n  <script src="popup.js">')
        popup = popup.replace("Pistachio for Safari", "Pistachio for " + target.title())
        instructions = ("Chrome › Extensions › Pistachio › Site access" if target == "chrome"
                        else "Firefox › Extensions › Pistachio › Permissions")
        popup = popup.replace("Safari › Settings › Extensions › Pistachio", instructions)
        (stage / "popup.html").write_text(popup)
        (stage / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
        destination = output / target
        if destination.exists() or destination.is_symlink():
            marker = destination / ".pistachio-generated"
            if destination.is_symlink() or not marker.is_file() or marker.read_text() != target:
                raise ValueError("refusing to replace a directory not generated by this builder")
            shutil.rmtree(destination)
        shutil.copytree(stage, destination)
        (destination / ".pistachio-generated").write_text(target)
        archive = output / ("pistachio-" + target + (".zip" if target == "chrome" else ".xpi"))
        with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as zipped:
            for path in sorted(stage.iterdir()):
                info = zipfile.ZipInfo(path.name, date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o100644 << 16
                zipped.writestr(info, path.read_bytes())
        return {"target": target, "version": manifest["version"], "archive": archive.name,
                "sha256": hashlib.sha256(archive.read_bytes()).hexdigest(),
                "status": "development build; native helper setup required; not store-signed"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "build/browser-extensions")
    args = parser.parse_args()
    output = args.output.resolve()
    # Generated destinations are fixed children; do not overwrite canonical resource directories.
    if output == ROOT or ROOT / "App" == output or ROOT / "App" in output.parents:
        parser.error("choose a build output directory outside App")
    output.mkdir(parents=True, exist_ok=True)
    results = [package(target, output) for target in ("chrome", "firefox")]
    (output / "build-info.json").write_text(json.dumps(results, indent=2) + "\n")
    for result in results:
        print(result["archive"], result["sha256"])


if __name__ == "__main__":
    main()
